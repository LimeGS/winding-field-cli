def run_flags(root,config):
    args=['--field-frame',config['frame'],'--field-voxel-um',str(config['voxel_um']),
          '--sheet-step',str(config['sheet_step']),'--calibration',config['calibration']]
    for name in ('origin_xyz','spacing_xyz','shape_zyx'):
        args+=['--grid-'+name.replace('_','-'),*map(str,config['grid'][name])]
    for name,value in {**config['observations'],**{k:config[k] for k in ('fixed','constraints','order') if k in config}}.items():
        args+=['--'+name,str((root/value['path']).resolve()),'--'+name+'-sha256',value['sha256']]
    for section in ('solver','execution'):
        for name,value in config[section].items():args+=['--'+name.replace('_','-'),str(value)]
    for key,value in config.get('source_identity',{}).items():
        args+=['--source-identity',key,json.dumps(value)]
    return args


def pins(root):
    return {str(p.relative_to(root)):(file_sha(p),p.stat().st_mtime_ns)
            for p in root.rglob('*') if p.is_file()}


def test_maximal_flag_request_matches_native_config_science(tmp_path):
    path,config=prepared(tmp_path,fixed=True,constraints=True)
    order=tmp_path/'inputs/order.npy';np.save(order,np.array([[0,0,0],[0,0,1]],dtype='i8'))
    config['order']=dict(path='inputs/order.npy',sha256=sha(order))
    config['source_identity']={'instrument':'synthetic','nested':{'channels':[1,False,None]}}
    config['solver'].update(device='cpu',preconditioner='jacobi')
    config['execution'].update(cache_bytes=0,read_workers=1,constraint_cache_bytes=0,
                                prepared_cache_bytes=0,max_bytes=8<<20,reserve_bytes=0)
    path.write_text(json.dumps(config))
    reference=tmp_path/'file';actual=tmp_path/'flags'
    field_workflow.run_field(path,reference)
    assert field_workflow.main(['build','--output',str(actual),*run_flags(tmp_path,config)])==0
    a,x,support=stored(reference);b,y,valid=stored(actual)
    assert a['identity']==b['identity']
    np.testing.assert_array_equal(x,y);np.testing.assert_array_equal(support,valid)
    metadata=json.loads((actual/'RUN.json').read_bytes())
    assert Path(metadata['config_path']).is_file()
    assert metadata['identity']['source_identity']==config['source_identity']


def test_prepared_resume_without_user_config_reuses_saved_request(tmp_path):
    _,config=prepared(tmp_path)
