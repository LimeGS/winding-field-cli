def test_gpu_flags_survive_validation_before_resource_denial(tmp_path,monkeypatch):
    from field_runtime import GpuLease,ResourceUnavailable
    _,config=prepared(tmp_path);root=tmp_path/'field'
    config['solver']['device']='cuda:0'
    monkeypatch.setenv('CUDA_VISIBLE_DEVICES','GPU-synthetic')
    def unavailable(self):raise ResourceUnavailable('test has no hardware lease')
    monkeypatch.setattr(GpuLease,'__enter__',unavailable)
    assert field_workflow.main(['build','--output',str(root),*run_flags(tmp_path,config),
        '--gpu-index','3','--gpu-uuid','GPU-synthetic','--gpu-lock-path',str(tmp_path/'lease.lock'),
        '--gpu-min-free-bytes','0','--gpu-deadline','4000000000'])==75
    recipe=next(tmp_path.glob('field.request-*.json'))
    assert field_workflow.load_run_config(recipe)['gpu']=={
        'index':3,'uuid':'GPU-synthetic','lock_path':str(tmp_path/'lease.lock'),
        'min_free_bytes':0,'deadline':4e9}
    assert not (tmp_path/'lease.lock').exists()


